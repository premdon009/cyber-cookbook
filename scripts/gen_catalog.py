"""Render docs/resources/*.md from resources.yml.

Usage:  uv run python scripts/gen_catalog.py [--check]
--check exits 1 if the generated pages differ from what is on disk (used in CI).
"""

from __future__ import annotations

import sys
from pathlib import Path

from _resources import ROOT, load

OUT = ROOT / "docs" / "resources"
HEADER = "<!-- GENERATED by scripts/gen_catalog.py from resources.yml - do not edit by hand -->\n\n"
COST_BADGE = {"free": "🟢 free", "freemium": "🟡 freemium", "self-hosted": "🔵 self-hosted"}


def _cell(text: str) -> str:
    return str(text).replace("|", "\\|")


def render_category(title: str, items: list[dict]) -> str:
    lines = [HEADER, f"# {title}\n\n", f"{len(items)} resources.\n\n"]
    lines.append("| Resource | Level | Cost | Platform | Team | Why / when |\n")
    lines.append("|---|---|---|---|---|---|\n")
    for r in sorted(items, key=lambda r: (r["level"], r["name"].lower())):
        name = f"[{_cell(r['name'])}]({r['url']})"
        if r.get("repo") and r["repo"] != r["url"]:
            name += f" · [repo]({r['repo']})"
        if r.get("clone"):
            name += " 📥"
        lines.append(
            f"| {name} | {r['level']} | {COST_BADGE[r['cost']]} | {r['platform']} "
            f"| {r['team']} | {_cell(r['note'])} |\n"
        )
    lines.append("\n📥 = cloned for offline reading by `scripts/fetch_resources.py`.\n")
    return "".join(lines)


def render_index(categories: dict[str, str], resources: list[dict]) -> str:
    lines = [HEADER, "# Resource catalog\n\n"]
    lines.append(
        "Every external resource used in the cookbook, generated from "
        "[`resources.yml`](https://github.com/premdon009/cyber-cookbook/blob/main/resources.yml).\n\n"
        "**Cost legend:** 🟢 free · 🟡 freemium (free tier is enough to learn, paid tier exists) · "
        "🔵 self-hosted (free, runs in your own lab).\n\n"
    )
    lines.append("| Category | Count |\n|---|---|\n")
    for key, title in categories.items():
        n = sum(1 for r in resources if r["category"] == key)
        lines.append(f"| [{title}]({key}.md) | {n} |\n")
    lines.append(f"\n**Total:** {len(resources)}\n")
    return "".join(lines)


def build() -> dict[Path, str]:
    categories, resources = load()
    pages = {OUT / "index.md": render_index(categories, resources)}
    for key, title in categories.items():
        items = [r for r in resources if r["category"] == key]
        pages[OUT / f"{key}.md"] = render_category(title, items)
    return pages


def main() -> int:
    check = "--check" in sys.argv
    pages = build()
    stale = [p for p, text in pages.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if check:
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)}")
        return 1 if stale else 0
    OUT.mkdir(parents=True, exist_ok=True)
    for p, text in pages.items():
        p.write_text(text, encoding="utf-8")
    print(f"wrote {len(pages)} pages ({len(stale)} changed) to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
